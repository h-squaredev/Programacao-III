public class TrueOrFalse {
        static boolean var1 = true;
        static boolean var2 = false;
        static boolean var3 = true;
        public static void main(String[] args) {
            if (var1) {
                System.out.println("A var1 é verdadeira!");
            }else{
                System.out.println("A var1 é falsa!");
            }
            if (var2) {
                System.out.println("A var2 é verdadeira!");
            }else{
                System.out.println("A var2 é falsa!");
            }
            if (var3) {
                System.out.println("A var3 é verdadeira!");
            }else{
                System.out.println("A var3 é falsa!");
            }
        }
    }
